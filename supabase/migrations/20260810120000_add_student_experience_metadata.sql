-- Additive metadata for grade-aware matching, time estimates, and auditable
-- scholarship verification. Existing scholarship values are not rewritten.

alter table if exists public.scholarships
  add column if not exists eligible_grade_levels text[] not null default '{}',
  add column if not exists last_verified_at timestamptz,
  add column if not exists deadline_verified_at timestamptz,
  add column if not exists source_url text,
  add column if not exists scholarship_status text not null default 'needs_verification',
  add column if not exists application_cycle text,
  add column if not exists estimated_completion_minutes integer;

alter table if exists public.tasks
  add column if not exists estimated_completion_minutes integer,
  add column if not exists task_priority text not null default 'normal';

do $$
begin
  if to_regclass('public.scholarships') is not null then
    alter table public.scholarships
      drop constraint if exists scholarships_estimated_completion_minutes_check;
    alter table public.scholarships
      add constraint scholarships_estimated_completion_minutes_check
      check (estimated_completion_minutes is null or estimated_completion_minutes between 1 and 1440);

    alter table public.scholarships
      drop constraint if exists scholarships_status_check;
    alter table public.scholarships
      add constraint scholarships_status_check
      check (scholarship_status in ('active', 'inactive', 'expired', 'needs_verification'));
  end if;

  if to_regclass('public.tasks') is not null then
    alter table public.tasks
      drop constraint if exists tasks_estimated_completion_minutes_check;
    alter table public.tasks
      add constraint tasks_estimated_completion_minutes_check
      check (estimated_completion_minutes is null or estimated_completion_minutes between 1 and 1440);

    alter table public.tasks
      drop constraint if exists tasks_task_priority_check;
    alter table public.tasks
      add constraint tasks_task_priority_check
      check (task_priority in ('low', 'normal', 'high', 'urgent'));
  end if;
end $$;

create table if not exists public.scholarship_verification_audit (
  id bigint generated by default as identity primary key,
  scholarship_id uuid not null references public.scholarships(id) on delete cascade,
  changed_at timestamptz not null default now(),
  changed_by uuid default auth.uid(),
  source_url text,
  change_source text not null default 'manual',
  previous_values jsonb not null,
  new_values jsonb not null
);

create index if not exists scholarship_verification_audit_scholarship_idx
  on public.scholarship_verification_audit (scholarship_id, changed_at desc);

alter table public.scholarship_verification_audit enable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'scholarship_verification_audit'
      and policyname = 'Authenticated users can read scholarship verification history'
  ) then
    create policy "Authenticated users can read scholarship verification history"
      on public.scholarship_verification_audit
      for select
      to authenticated
      using (true);
  end if;
end $$;

create or replace function public.audit_scholarship_verification_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  old_verification jsonb;
  new_verification jsonb;
begin
  old_verification := jsonb_build_object(
    'deadline', old.deadline,
    'deadline_raw', old.deadline_raw,
    'grade_requirement', old.grade_requirement,
    'eligible_grade_levels', old.eligible_grade_levels,
    'status', old.status,
    'scholarship_status', old.scholarship_status,
    'application_cycle', old.application_cycle,
    'source_url', old.source_url,
    'last_verified_at', old.last_verified_at,
    'deadline_verified_at', old.deadline_verified_at
  );
  new_verification := jsonb_build_object(
    'deadline', new.deadline,
    'deadline_raw', new.deadline_raw,
    'grade_requirement', new.grade_requirement,
    'eligible_grade_levels', new.eligible_grade_levels,
    'status', new.status,
    'scholarship_status', new.scholarship_status,
    'application_cycle', new.application_cycle,
    'source_url', new.source_url,
    'last_verified_at', new.last_verified_at,
    'deadline_verified_at', new.deadline_verified_at
  );

  if old_verification is distinct from new_verification then
    insert into public.scholarship_verification_audit (
      scholarship_id,
      source_url,
      previous_values,
      new_values
    ) values (
      new.id,
      new.source_url,
      old_verification,
      new_verification
    );
  end if;
  return new;
end;
$$;

drop trigger if exists scholarships_verification_audit on public.scholarships;
create trigger scholarships_verification_audit
after update on public.scholarships
for each row execute function public.audit_scholarship_verification_change();

comment on table public.scholarship_verification_audit is
  'Append-only history for deadline, eligibility, status, cycle, and source verification changes.';
